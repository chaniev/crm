import { expect, test } from '@playwright/test'

test('real PostgreSQL search preserves full names and recovers from errors', async ({ page }, info) => {
  await page.goto('/login')
  await page.getByRole('textbox', { name: 'Логин', exact: true }).fill('HeadCoach')
  await page.getByLabel('Пароль', { exact: true }).fill('branch-settings-password')
  const login = page.waitForResponse(r => r.url().endsWith('/api/auth/login'))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  expect((await login).ok()).toBe(true)
  await expect(page.getByRole('textbox', { name: 'Логин', exact: true })).toHaveCount(0)
  await page.goto('/clients')
  const input = page.getByRole('textbox', { name: 'Поиск по имени или телефону', exact: true })
  for (const query of ['Алексеев', 'Алексеев Алексей', 'Алексеев Алексей Дмитриевич']) {
    const response = page.waitForResponse(r => new URL(r.url()).pathname === '/api/clients' && new URL(r.url()).searchParams.get('query') === query)
    await input.fill(query)
    const result = await (await response).json()
    await info.attach(`query-${query}.json`, { body: JSON.stringify({ query, role: 'HeadCoach', result }), contentType: 'application/json' })
    expect(result.totalCount).toBe(1)
    expect(result.items[0].fullName).toBe('Алексеев Алексей Дмитриевич')
    await expect(page.getByText('Алексеев Алексей Дмитриевич', { exact: true }).first()).toBeVisible()
  }
  await input.focus()
  await expect(input).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(input).not.toBeFocused()
  await page.screenshot({ path: info.outputPath('full-name.png'), fullPage: true })
  await info.attach('search-dom.txt', { body: await page.locator('body').ariaSnapshot(), contentType: 'text/plain' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByText('Алексеев Алексей Дмитриевич', { exact: true }).first().click()
  await page.getByRole('button', { name: 'Открыть карточку', exact: true }).click()
  await expect(page).toHaveURL(/\/clients\/[^/?]+/)
  await page.getByRole('button', { name: 'К списку клиентов', exact: true }).click()
  await expect(input).toHaveValue('Алексеев Алексей Дмитриевич')
  await input.fill('Несуществующий')
  await expect(page.getByRole('button', { name: 'Очистить поиск', exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Очистить поиск', exact: true }).first().click()
  await expect(input).toHaveValue('')
  await page.route('**/api/clients?**', route => route.fulfill({ status: 500, contentType: 'application/problem+json', body: JSON.stringify({ title: 'Ошибка поиска' }) }), { times: 1 })
  await input.fill('Алексеев Алексей')
  await page.getByRole('button', { name: 'Повторить', exact: true }).first().click()
  await expect(page.getByText('Алексеев Алексей Дмитриевич', { exact: true }).first()).toBeVisible()
})

test('coach receives only assigned client and no phone search', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('textbox', { name: 'Логин', exact: true }).fill('Coach')
  await page.getByLabel('Пароль', { exact: true }).fill('branch-settings-password')
  const login = page.waitForResponse(r => r.url().endsWith('/api/auth/login'))
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  expect((await login).ok()).toBe(true)
  await expect(page.getByRole('textbox', { name: 'Логин', exact: true })).toHaveCount(0)
  await page.goto('/clients')
  const input = page.getByRole('textbox', { name: 'Поиск по имени', exact: true })
  const result = page.waitForResponse(r => new URL(r.url()).pathname === '/api/clients' && new URL(r.url()).searchParams.get('query') === 'Алексеев Алексей')
  await input.fill('Алексеев Алексей')
  expect((await (await result).json()).totalCount).toBe(1)
  await expect(page.getByText('+79990000001', { exact: true })).toHaveCount(0)
  const phone = page.waitForResponse(r => new URL(r.url()).searchParams.get('query') === '79990000001')
  await input.fill('79990000001')
  expect((await (await phone).json()).totalCount).toBe(0)
})
